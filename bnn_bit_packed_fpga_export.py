# ---------------- utils -----------------
def one_hot(y, n=10):
    t = np.zeros((y.size, n), dtype=np.float32)
    t[np.arange(y.size), y] = 1.0
    return t

def softmax(x):
    ex = np.exp(x - np.max(x, axis=1, keepdims=True))
    return ex / np.sum(ex, axis=1, keepdims=True)

def cross_entropy(p, y):
    eps = 1e-9
    return -np.mean(np.sum(y * np.log(p + eps), axis=1))

def popcount32_np(arr):
    try:
        return arr.view(np.uint32).bit_count()
    except Exception:
        v = np.array([int(x).bit_count() for x in arr.ravel()], dtype=np.int32)
        return v.reshape(arr.shape)

def pack_bits_row(bits):
    L = len(bits)
    words = (L + 31)//32
    out = np.zeros(words, dtype=np.uint32)
    for i in range(words):
        chunk = bits[i*32:(i+1)*32]
        val = 0
        for j, b in enumerate(chunk):
            if int(b):
                val |= (1 << j)
        out[i] = np.uint32(val)
    return out

def pack_bits_matrix(binmat):
    rows, cols = binmat.shape
    words = (cols + 31) // 32
    out = np.zeros((rows, words), dtype=np.uint32)
    for r in range(rows):
        out[r] = pack_bits_row(binmat[r])
    return out

def binarize_x(x, thresh=0.25):
    return (x > thresh).astype(np.uint8)

