def ensure_mnist_loaded():
    """Ensure x_test and y_test are available as globals (normalized float images)."""
    global x_test, y_test
    try:
        _ = x_test, y_test
    except NameError:
        (_, _), (x_test_raw, y_test_raw) = mnist.load_data()
        x_test = x_test_raw.reshape(-1, INPUT).astype(np.float32) / 255.0
        y_test = y_test_raw
    return x_test, y_test

def load_model_from_npz(path, model):
    """Load float params stored by model.save_npz into an existing model instance."""
    if not os.path.exists(path):
        raise FileNotFoundError(f"Saved model not found at: {path}")
    d = np.load(path)
    model.w1 = d["w1"].astype(np.float32)
    model.b1 = d["b1"].astype(np.float32)
    model.w2 = d["w2"].astype(np.float32)
    model.b2 = d["b2"].astype(np.float32)
    model.gamma1 = d["gamma1"].astype(np.float32)
    model.beta1  = d["beta1"].astype(np.float32)
    model.gamma2 = d["gamma2"].astype(np.float32)
    model.beta2  = d["beta2"].astype(np.float32)
    return model

def test_single_mnist(model=None, use_saved_if_needed=True, save_path=SAVE_PATH, show_image=True):
    """
    Ask the user for an integer index (or press Enter for random), show the 28x28 image,
    run model.forward_float() and print predicted class + top-3 probabilities.

    - model: an existing XNOR_BNN_Model instance (if None, we will create one and try to load saved params).
    - use_saved_if_needed: if True and model is None, attempt to load parameters from save_path.
    """
    x_test, y_test = ensure_mnist_loaded()

    # prepare model
    if model is None:
        if not use_saved_if_needed:
            raise ValueError("No model provided and use_saved_if_needed is False.")
        # build fresh model instance and try to load saved params
        model = XNOR_BNN_Model(INPUT, HIDDEN, OUTPUT, lr=LR)
        try:
            model = load_model_from_npz(save_path, model)
            print("Loaded saved params from", save_path)
        except Exception as e:
            print("Warning: could not load saved params:", e)
            print("Using randomly initialized model (predictions will be meaningless).")

    # ask user for an index (or random)
    prompt = f"Enter an index (0..{x_test.shape[0]-1}) or press Enter for a random MNIST test image: "
    s = input(prompt).strip()
    if s == "":
        idx = np.random.randint(0, x_test.shape[0])
    else:
        try:
            idx = int(s) % x_test.shape[0]
        except Exception:
            print("Invalid input: using a random index.")
            idx = np.random.randint(0, x_test.shape[0])

    img_flat = x_test[idx:idx+1]  # shape (1, 784)
    gt_label = int(y_test[idx])
    img_2d = (img_flat.reshape(28, 28) * 255).astype(np.uint8)

    # display image
    if show_image:
        plt.figure(figsize=(3,3))
        plt.imshow(img_2d, cmap="gray", interpolation="nearest")
        plt.axis("off")
        plt.title(f"Index: {idx}    Label: {gt_label}")
        plt.show()

    # forward pass
    probs, _ = model.forward_float(img_flat)
    probs = probs.ravel().astype(np.float32)
    pred = int(np.argmax(probs))
    # top-3
    top3_idx = np.argsort(probs)[::-1][:3]

    print(f"\nGround-truth label: {gt_label}")
    print(f"Model predicted class: {pred}")
    print("Top-3 probabilities:")
    for i in top3_idx:
        print(f"  class {i}: {probs[i]*100:.2f}%")

    return {"index": idx, "label": gt_label, "pred": pred, "probs": probs}

