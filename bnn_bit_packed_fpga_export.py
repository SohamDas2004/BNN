# --------------- model ------------------
class XNOR_BNN_Model:
    def __init__(self, input_dim, hidden, out, lr=1e-3):
        self.inp = input_dim
        self.h = hidden
        self.out = out

        self.w1 = np.random.randn(self.inp, self.h).astype(np.float32) * 0.05
        self.b1 = np.zeros((1, self.h), dtype=np.float32)
        self.w2 = np.random.randn(self.h, self.out).astype(np.float32) * 0.05
        self.b2 = np.zeros((1, self.out), dtype=np.float32)

        # simple BN parameters
        self.gamma1 = np.ones((1, self.h), dtype=np.float32)
        self.beta1  = np.zeros((1, self.h), dtype=np.float32)
        self.gamma2 = np.ones((1, self.out), dtype=np.float32)
        self.beta2  = np.zeros((1, self.out), dtype=np.float32)

        self.lr = lr

        # Adam state
        self.adam_state = {}
        for name, p in [("w1", self.w1), ("b1", self.b1),
                        ("w2", self.w2), ("b2", self.b2),
                        ("g1", self.gamma1), ("bta1", self.beta1),
                        ("g2", self.gamma2), ("bta2", self.beta2)]:
            self.adam_state[name] = {"m": np.zeros_like(p), "v": np.zeros_like(p), "t": 0}

    def adam_step(self, name, param, grad, lr=None):
        if lr is None:
            lr = self.lr
        s = self.adam_state[name]
        b1, b2 = 0.9, 0.999
        eps = 1e-8
        s["t"] += 1
        s["m"] = b1 * s["m"] + (1 - b1) * grad
        s["v"] = b2 * s["v"] + (1 - b2) * (grad * grad)
        mhat = s["m"] / (1 - b1 ** s["t"])
        vhat = s["v"] / (1 - b2 ** s["t"])
        step = lr * mhat / (np.sqrt(vhat) + eps)
        param -= step
        return param

    def binary_weight_float(self, alpha=1.0):
        w1_sign = np.sign(self.w1)
        w1_sign[w1_sign == 0] = 1.0
        w2_sign = np.sign(self.w2)
        w2_sign[w2_sign == 0] = 1.0

        scale1 = np.mean(np.abs(self.w1), axis=0, keepdims=True) + 1e-12
        scale2 = np.mean(np.abs(self.w2), axis=0, keepdims=True) + 1e-12

        w1_b = w1_sign * scale1
        w2_b = w2_sign * scale2
        return w1_b.astype(np.float32), w2_b.astype(np.float32)

    def forward_float(self, X, alpha=1.0):
        w1_b, w2_b = self.binary_weight_float(alpha)
        z1 = X.dot(w1_b) + self.b1
        mu1 = np.mean(z1, axis=0, keepdims=True)
        std1 = np.std(z1, axis=0, keepdims=True) + 1e-5
        x1 = (z1 - mu1) / std1
        z1a = self.gamma1 * x1 + self.beta1
        a1 = np.clip(z1a, -1.0, 1.0)

        z2 = a1.dot(w2_b) + self.b2
        mu2 = np.mean(z2, axis=0, keepdims=True)
        std2 = np.std(z2, axis=0, keepdims=True) + 1e-5
        x2 = (z2 - mu2) / std2
        z2a = self.gamma2 * x2 + self.beta2
        out = softmax(z2a)
        return out, (w1_b, w2_b, z1, x1, z1a, a1, z2, x2, z2a)

    def backward_and_update(self, X, y, internals, lr=None):
        out, (w1_b, w2_b, z1, x1, z1a, a1, z2, x2, z2a) = internals
        if lr is None:
            lr = self.lr
        m = X.shape[0]

        # output
        dz2a = (out - y) / m
        dgamma2 = np.sum(dz2a * x2, axis=0, keepdims=True)
        dbeta2  = np.sum(dz2a, axis=0, keepdims=True)
        dz2 = dz2a * self.gamma2
        dw2_b = a1.T.dot(dz2)
        db2   = np.sum(dz2, axis=0, keepdims=True)

        # hidden
        da1 = dz2.dot(w2_b.T)
        dact = (np.abs(z1a) <= 1.0).astype(np.float32)
        dz1a = da1 * dact

        dgamma1 = np.sum(dz1a * x1, axis=0, keepdims=True)
        dbeta1  = np.sum(dz1a, axis=0, keepdims=True)
        dz1 = dz1a * self.gamma1
        dw1_b = X.T.dot(dz1)
        db1   = np.sum(dz1, axis=0, keepdims=True)

        # STE for real weights
        ste_mask_w1 = (np.abs(self.w1) <= 1.0).astype(np.float32)
        ste_mask_w2 = (np.abs(self.w2) <= 1.0).astype(np.float32)
        dw1 = dw1_b * ste_mask_w1
        dw2 = dw2_b * ste_mask_w2

        # gradient clipping
        maxg = 5.0
        dw1 = np.clip(dw1, -maxg, maxg)
        dw2 = np.clip(dw2, -maxg, maxg)
        db1 = np.clip(db1, -maxg, maxg)
        db2 = np.clip(db2, -maxg, maxg)

        # adam updates
        self.w1 = self.adam_step("w1", self.w1, dw1, lr)
        self.b1 = self.adam_step("b1", self.b1, db1, lr)
        self.w2 = self.adam_step("w2", self.w2, dw2, lr)
        self.b2 = self.adam_step("b2", self.b2, db2, lr)
        self.gamma1 = self.adam_step("g1", self.gamma1, dgamma1, lr)
        self.beta1  = self.adam_step("bta1", self.beta1, dbeta1, lr)
        self.gamma2 = self.adam_step("g2", self.gamma2, dgamma2, lr)
        self.beta2  = self.adam_step("bta2", self.beta2, dbeta2, lr)

        # keep real weights in [-1,1]
        self.w1 = np.clip(self.w1, -1.0, 1.0)
        self.w2 = np.clip(self.w2, -1.0, 1.0)

    # ---------- bitpacked conversion for FPGA ----------
    def build_bitpacked(self, calib_samples=6000):
        """
        Build bitpacked weights + calibrated thresholds TH1 (hidden) and TH2 (output)
        using the validation set. These are what you will use in FPGA.
        """

        # 1) PACK WEIGHTS (±1 -> {0,1} bits -> uint32 words)

        # W1: [INPUT, HIDDEN] -> bits [HIDDEN, INPUT] -> packed [HIDDEN, WORDS_INPUT]
        w1_sign = np.sign(self.w1)
        w1_sign[w1_sign == 0] = 1.0
        w1_bits = ((w1_sign.T + 1.0) / 2.0).astype(np.uint8)
        W1_packed = pack_bits_matrix(w1_bits)

        # W2: [HIDDEN, OUTPUT] -> bits [OUTPUT, HIDDEN] -> packed [OUTPUT, WORDS_HIDDEN]
        w2_sign = np.sign(self.w2)
        w2_sign[w2_sign == 0] = 1.0
        w2_bits = ((w2_sign.T + 1.0) / 2.0).astype(np.uint8)
        W2_packed = pack_bits_matrix(w2_bits)

        # 2) CALIBRATION DATA (from global x_val / y_val)
        global x_val, y_val
        n_cal = min(calib_samples, x_val.shape[0])
        Xcal = x_val[:n_cal]
        Ycal_oh = y_val[:n_cal]
        Ycal_labels = np.argmax(Ycal_oh, axis=1)

        # 3) FLOAT HIDDEN ACTIVATION SIGN AS TARGET FOR TH1
        _, internals = self.forward_float(Xcal)
        a1_float = internals[5]                      # shape [n_cal, HIDDEN]
        hidden_target = (a1_float > 0).astype(np.uint8)  # [n_cal, HIDDEN]

        # 4) BINARIZE INPUTS & PACK (MUST MATCH FPGA INPUT BINARIZATION)
        n_words_input = (self.inp + 31) // 32
        inputs_packed = np.zeros((n_cal, n_words_input), dtype=np.uint32)
        for i in range(n_cal):
            b = (Xcal[i] > 0.25).astype(np.uint8)    # same threshold as binarize_x
            inputs_packed[i] = pack_bits_row(b)

        # 5) CALIBRATE TH1 + BUILD PACKED HIDDEN LAYER FOR CAL SAMPLES
        H = self.h
        TH1 = np.zeros(H, dtype=np.int32)

        n_words_hidden = (H + 31) // 32
        hidden_packed_cal = np.zeros((n_cal, n_words_hidden), dtype=np.uint32)

        for h in range(H):
            wwords = W1_packed[h]  # [WORDS_INPUT]

            xor = np.bitwise_xor(inputs_packed, wwords)
            xnor = np.bitwise_not(xor).astype(np.uint32)
            pc = np.sum(popcount32_np(xnor), axis=1)  # [n_cal]

            target = hidden_target[:, h]
            candidates = np.unique(pc)

            best_acc = -1
            best_T = int(self.inp // 2)
            for T in candidates:
                pred = (pc >= T).astype(np.uint8)
                acc = (pred == target).sum()
                if acc > best_acc:
                    best_acc = acc
                    best_T = int(T)

            TH1[h] = best_T

            # pack hidden bits for this neuron
            pred_final = (pc >= TH1[h]).astype(np.uint8)  # [n_cal]
            word_idx = h // 32
            bit_off = h % 32
            mask_vec = (pred_final.astype(np.uint32) << bit_off)
            hidden_packed_cal[:, word_idx] |= mask_vec

        # 6) CALIBRATE TH2 USING CLASS LABELS
        O = self.out
        TH2 = np.zeros(O, dtype=np.int32)

        # score2[o, i] = 2*popcount(XNOR(hidden_bits_i, W2[o])) - H
        score2 = np.zeros((O, n_cal), dtype=np.int32)

        for o in range(O):
            wwords2 = W2_packed[o]  # [WORDS_HIDDEN]
            xor2 = np.bitwise_xor(hidden_packed_cal, wwords2)
            xnor2 = np.bitwise_not(xor2).astype(np.uint32)
            pc2 = np.sum(popcount32_np(xnor2), axis=1)  # [n_cal]
            s2 = 2 * pc2 - H
            score2[o, :] = s2

        for o in range(O):
            mask = (Ycal_labels == o)
            if np.any(mask):
                TH2[o] = int(np.median(score2[o, mask]))
            else:
                TH2[o] = int(np.median(score2[o, :]))

        # store for later use (if needed)
        self.W1_packed = W1_packed
        self.W2_packed = W2_packed
        self.TH1 = TH1
        self.TH2 = TH2

        return W1_packed, W2_packed, TH1, TH2

    def update_bitpacked_from_current(self):
        self.W1_packed, self.W2_packed, self.TH1, self.TH2 = self.build_bitpacked()

    def save_npz(self, path):
        np.savez_compressed(
            path,
            w1=self.w1, b1=self.b1,
            w2=self.w2, b2=self.b2,
            gamma1=self.gamma1, beta1=self.beta1,
            gamma2=self.gamma2, beta2=self.beta2
        )

