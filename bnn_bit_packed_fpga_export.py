def save_hex_matrix(filename, mat):
    """
    Save 2D uint32 matrix as HEX lines.
    Each line is one 32-bit word in big-endian hex (8 chars).
    """
    with open(filename, "w") as f:
        for row in mat:
            for val in row:
                f.write(f"{int(val) & 0xFFFFFFFF:08X}\n")

def save_hex_vector(filename, vec):
    """
    Save 1D int vector as HEX lines (32-bit).
    """
    with open(filename, "w") as f:
        for v in vec:
            f.write(f"{int(v) & 0xFFFFFFFF:08X}\n")


